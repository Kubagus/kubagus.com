CREATE TABLE IF NOT EXISTS projects (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  site_id INT UNSIGNED NOT NULL,
  slug VARCHAR(150) NOT NULL,
  title_id VARCHAR(200) NULL,
  title_en VARCHAR(200) NULL,
  summary_id TEXT NULL,
  summary_en TEXT NULL,
  content_id MEDIUMTEXT NULL,
  content_en MEDIUMTEXT NULL,
  cover_image VARCHAR(255) NULL,
  tech_stack JSON NULL,
  github_url VARCHAR(255) NULL,
  demo_url VARCHAR(255) NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  is_published TINYINT(1) NOT NULL DEFAULT 0,
  published_at DATETIME NULL,
  sort_order INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_projects_site FOREIGN KEY (site_id) REFERENCES sites(id) ON DELETE CASCADE,
  UNIQUE KEY uq_projects_site_slug (site_id, slug),
  KEY idx_projects_site (site_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

